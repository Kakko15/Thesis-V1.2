@pytest.mark.parametrize('question', MUST_REFUSE)
def test_requests_to_author_thesis_content_are_refused(question):
    assert prohibited_reason(question) is not None, question


@pytest.mark.parametrize('question', MUST_ALLOW)
def test_legitimate_retrieval_questions_are_never_refused(question):
    assert prohibited_reason(question) is None, question


def test_the_corpora_do_not_overlap():
    assert not set(MUST_REFUSE) & set(MUST_ALLOW)
